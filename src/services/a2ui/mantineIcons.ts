/** Lucide icon for a semantic name, or null when the name is unknown. */
export function getIcon(iconName?: string): LucideIcon | null {
	if (!iconName) return null
	const normalized = iconName.toLowerCase().replace(/[-_\s]/g, '')
	return ICON_MAP[normalized] ?? null
}
